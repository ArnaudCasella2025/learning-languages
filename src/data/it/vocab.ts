import type { VocabItem } from "../../types";

/**
 * Deck de vocabulaire italien courant, classé par catégorie.
 * "tier 1" = coeur du vocabulaire de survie (niveau 1), introduit en premier.
 * "tier 2" = vocabulaire de continuation (niveau 2+), débloqué progressivement.
 *
 * Ce n'est pas (encore) une liste de fréquence de 1000 mots vérifiée : c'est
 * un socle solide et organisé, pensé pour être complété facilement dans ce
 * fichier (voir README) au fur et à mesure que tu progresses.
 */
function w(it: string, fr: string, category: string, tier: 1 | 2 = 1): VocabItem {
  return { id: `${category}-${it}`, it, fr, category, tier };
}

