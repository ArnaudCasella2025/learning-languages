import type { VocabItem } from "../../types";

/**
 * Deck de vocabulaire arabe (arabe standard moderne / فصحى), classé par
 * catégorie. "tier 1" = coeur du vocabulaire de survie (niveau 1), introduit
 * en premier. "tier 2" = vocabulaire de continuation (niveau 2+).
 *
 * La translittération est un repère de lecture simplifié (pas une norme
 * académique) : ' note aussi bien la hamza (ء) que le ayn (ع), les voyelles
 * longues sont doublées (aa/ii/uu). Elle sert de béquille au début — l'idée
 * est de s'appuyer de plus en plus sur la lecture de l'écriture arabe et sur
 * la voix de synthèse, pas de rester dépendant de la translittération.
 *
 * Comme pour l'italien, ce n'est pas une liste de fréquence vérifiée : c'est
 * un socle solide et organisé, à compléter dans ce fichier au fil de la
 * progression (voir README).
 */
function w(ar: string, fr: string, translit: string, category: string, tier: 1 | 2 = 1): VocabItem {
  return { id: `${category}-${ar}`, it: ar, fr, translit, category, tier };
}

